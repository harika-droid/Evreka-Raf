CREATE DATABASE IF NOT EXISTS evrekaraf CHARACTER SET utf8mb4 COLLATE utf8mb4_turkish_ci;
USE evrekaraf;

CREATE TABLE IF NOT EXISTS users (
  id VARCHAR(40) PRIMARY KEY, email VARCHAR(190) UNIQUE, kadi VARCHAR(80), ad VARCHAR(120),
  role VARCHAR(20) DEFAULT 'user', status VARCHAR(20), il VARCHAR(60), ilce VARCHAR(60),
  created BIGINT, data LONGTEXT NOT NULL);
CREATE TABLE IF NOT EXISTS books (
  id VARCHAR(40) PRIMARY KEY, owner_id VARCHAR(40), ad VARCHAR(255), yazar VARCHAR(255), kat VARCHAR(80),
  tur VARCHAR(20), il VARCHAR(60), status VARCHAR(20), created BIGINT, data LONGTEXT NOT NULL,
  INDEX ix_books_owner (owner_id));
CREATE TABLE IF NOT EXISTS requests (
  id VARCHAR(40) PRIMARY KEY, book_id VARCHAR(40), from_id VARCHAR(40), to_id VARCHAR(40),
  status VARCHAR(20), created BIGINT, data LONGTEXT NOT NULL, INDEX ix_req_book (book_id));
CREATE TABLE IF NOT EXISTS messages (
  id VARCHAR(40) PRIMARY KEY, req_id VARCHAR(40), from_id VARCHAR(40), t BIGINT, data LONGTEXT NOT NULL,
  INDEX ix_msg_req (req_id));
CREATE TABLE IF NOT EXISTS reviews (id VARCHAR(40) PRIMARY KEY, status VARCHAR(20), puan INT, created BIGINT, data LONGTEXT NOT NULL);
CREATE TABLE IF NOT EXISTS contacts (id VARCHAR(40) PRIMARY KEY, created BIGINT, data LONGTEXT NOT NULL);
CREATE TABLE IF NOT EXISTS notifs (
  id VARCHAR(40) PRIMARY KEY, uid VARCHAR(40), `read` TINYINT, t BIGINT, data LONGTEXT NOT NULL, INDEX ix_notif_uid (uid));
CREATE TABLE IF NOT EXISTS wishes (id VARCHAR(40) PRIMARY KEY, uid VARCHAR(40), ad VARCHAR(255), created BIGINT, data LONGTEXT NOT NULL);
CREATE TABLE IF NOT EXISTS ratings (
  id VARCHAR(40) PRIMARY KEY, req_id VARCHAR(40), from_id VARCHAR(40), to_id VARCHAR(40),
  stars INT, t BIGINT, data LONGTEXT NOT NULL, INDEX ix_rating_to (to_id));
CREATE TABLE IF NOT EXISTS reports (id VARCHAR(40) PRIMARY KEY, from_id VARCHAR(40), status VARCHAR(20), t BIGINT, data LONGTEXT NOT NULL);
CREATE TABLE IF NOT EXISTS clubs (
  id VARCHAR(40) PRIMARY KEY, ad VARCHAR(255), il VARCHAR(60), kat VARCHAR(80), owner_id VARCHAR(40),
  created BIGINT, data LONGTEXT NOT NULL);
CREATE TABLE IF NOT EXISTS announcements (id VARCHAR(40) PRIMARY KEY, hedef VARCHAR(60), t BIGINT, data LONGTEXT NOT NULL);
CREATE TABLE IF NOT EXISTS meta (k VARCHAR(80) PRIMARY KEY, v LONGTEXT);
